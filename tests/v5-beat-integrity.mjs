import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({entryPoints:['src/audio/beatIntegrity.ts','src/audio/eventAudit.ts'],bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent',outdir:'dist-tests'});
const imports=await Promise.all(result.outputFiles.map(f=>import('data:text/javascript;base64,'+Buffer.from(f.text).toString('base64'))));
const scan=imports.find(x=>typeof x.scanBeatIntegrity==='function').scanBeatIntegrity;
const audit=imports.find(x=>typeof x.eventRouteAudit==='function').eventRouteAudit;
const sr=8000,len=sr*3,x=new Float32Array(len);
for(let i=0;i<len;i++)x[i]=.20*Math.sin(2*Math.PI*420*i/sr);
const wrap=()=>({sampleRate:sr,length:len,duration:len/sr,numberOfChannels:1,getChannelData:c=>{assert.equal(c,0);return x}});
let report=scan(wrap());assert.equal(report.impulseCandidates.length,0,'clean sine has no impulses');
x[Math.round(.7*sr)]=.98;
for(let i=sr;i<sr+Math.round(sr*.02);i++)x[i]=0;
for(let i=2*sr;i<2*sr+1000;i++)x[i]=1;
report=scan(wrap());
assert.ok(report.impulseCandidates.some(t=>Math.abs(t-.7)<.02),'flag artificial digital impulse');
assert.ok(report.dropoutCandidates.some(t=>Math.abs(t-1)<.05),'flag artificial sudden silence');
assert.ok(report.clippedPercent>0,'flag clipping');
const settings={enabled:true,amount:.55,rear:.8,hrtf:false,presence:.72};
const events=[{id:1,source:'lead',at:.1,duration:1,path:'front-left-right',band:'voice',level:.95}];
const stems={lead:{buffer:wrap(),mute:false,solo:false}};
assert.equal(audit(events,settings,stems,3,false,false).length,1);
assert.equal(audit(events,{...settings,enabled:false},stems,3,false,false)[0].state,'off');
assert.equal(audit(events,settings,stems,3,true,false)[0].state,'off');
assert.equal(audit(events,settings,{lead:{...stems.lead,mute:true}},3,false,false)[0].state,'off');
console.log('V5 BEAT integrity & event routing: no-DSP safety tests PASS');
